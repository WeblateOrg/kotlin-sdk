package org.weblate.plugin.android.task

import java.io.File
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.weblate.plugin.android.Constants

/**
 * Task to generate a config class to access values supplied to extension by library
 * @see org.weblate.plugin.android.extension.WeblateAndroidPluginExtension
 */
internal abstract class GenerateConfigTask : DefaultTask() {

    @get:Input
    abstract val cdnUrl: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        group = Constants.WEBLATE_TASK_GROUP
        description = TASK_DESCRIPTION
    }

    @TaskAction
    fun generateConfig() {
        val outputDir = outputDirectory.get().asFile
        val serviceDir = File(outputDir, PATH_DIR_SERVICE).also { file ->
            file.mkdirs()
        }

        File(serviceDir, PATH_CLASS_CONFIG)
            .writeText("${NAME_PACKAGE_GENERATED}.${NAME_CLASS_GENERATED}")

        val packageFolder = File(outputDir, NAME_PACKAGE_GENERATED.replace('.', '/')).also { file ->
            file.mkdirs()
        }

        val file = File(packageFolder, "$NAME_CLASS_GENERATED.kt")
        val content = """
            |package $NAME_PACKAGE_GENERATED
            |
            |import $PATH_CLASS_CONFIG
            |
            |/**
            | * Generated by the Weblate Gradle Plugin. Do not modify manually.
            | */
            |public class $NAME_CLASS_GENERATED : ConfigProvider {
            |    override val cdnUrl: String = "${cdnUrl.get()}"
            |}
        """.trimMargin()

        file.writeText(content)
    }

    companion object {
        private const val TASK_DESCRIPTION = "Generates a build config class for Weblate"

        private const val NAME_CLASS_GENERATED = "WeblateConfigProvider"
        private const val NAME_PACKAGE_GENERATED = "org.weblate.android.generated"

        private const val PATH_CLASS_CONFIG = "org.weblate.android.ConfigProvider"
        private const val PATH_DIR_SERVICE = "META-INF/services"
    }
}
